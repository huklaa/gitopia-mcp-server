// GetGitignoreTemplate returns a .gitignore template by name (case-insensitive).
// If name is empty or unknown, returns the generic template.
func GetGitignoreTemplate(name string) string {
    key := strings.ToLower(strings.TrimSpace(name))
    if key == "" {
        key = "generic"
    }
    if tpl, ok := GitignoreTemplates[key]; ok {
        return tpl
    }
    return GitignoreTemplates["generic"]
}
