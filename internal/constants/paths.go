package constants

import (
    "path/filepath"
    "strings"
)

// Path constants for MCP Gitopia server
const (
	// MCPRootDir is the root directory name for MCP data
	MCPRootDir = ".mcp"
	
	// GitopiaDir is the Gitopia-specific subdirectory under MCP root
	GitopiaDir = "gitopia"
	
	// WorkspaceSubdir is the workspace subdirectory name
	WorkspaceSubdir = "workspace"
	
	// ConfigSubdir is the config subdirectory name
	ConfigSubdir = "config"
	
	// CacheSubdir is the cache subdirectory name
	CacheSubdir = "cache"
	
	// LogsSubdir is the logs subdirectory name
	LogsSubdir = "logs"
	
	// ConfigFileName is the default config file name
	ConfigFileName = "config.json"
)

// GetMCPGitopiaPath returns the standard MCP Gitopia path: .mcp/gitopia
func GetMCPGitopiaPath() string {
	return filepath.Join(MCPRootDir, GitopiaDir)
}

// GetMCPGitopiaWorkspacePath returns the standard workspace path: .mcp/gitopia/workspace
func GetMCPGitopiaWorkspacePath() string {
	return filepath.Join(MCPRootDir, GitopiaDir, WorkspaceSubdir)
}

// GetMCPGitopiaConfigPath returns the standard config path: .mcp/gitopia/config
func GetMCPGitopiaConfigPath() string {
	return filepath.Join(MCPRootDir, GitopiaDir, ConfigSubdir)
}

// GetMCPGitopiaCachePath returns the standard cache path: .mcp/gitopia/cache
func GetMCPGitopiaCachePath() string {
	return filepath.Join(MCPRootDir, GitopiaDir, CacheSubdir)
}

// GetMCPGitopiaLogsPath returns the standard logs path: .mcp/gitopia/logs
func GetMCPGitopiaLogsPath() string {
	return filepath.Join(MCPRootDir, GitopiaDir, LogsSubdir)
}

